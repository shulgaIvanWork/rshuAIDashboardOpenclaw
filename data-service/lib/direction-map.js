// Значения поля «направление при создании», которые НЕ являются направлением.
// Уходят в артефакты, в таблицы не попадают.
export const CREATED_DIR_EXCLUDE = ['blog'];

/**
 * Разбор одной сделки в каноническое направление.
 * @param {Array|string} productDirIds UF_CRM_1498466811 (ID или массив ID)
 * @param {string} createdText        UF_CRM_1744273716729 (текст при создании)
 * @param {Object} directions         dicts.directions { id → name }
 * @returns {{id:string|null, name:string|null, source:'product'|'created'|'excluded'|'none'|'unresolved'}}
 *   source: product — из товара; created — сведено из текста; excluded — мусор (артефакт);
 *           unresolved — текст без соответствия (показываем как есть, тоже артефакт); none — пусто.
 */
export function resolveDealDirection(productDirIds, createdText, directions = {}) {
  const ids = (Array.isArray(productDirIds) ? productDirIds : [productDirIds])
    .filter(v => v !== null && v !== undefined && String(v) !== '')
    .map(String);
  if (ids.length) {
    const id = ids[0];
    return { id, name: directions[id] || id, source: 'product' };
  }

  const t = String(createdText || '').trim();
  if (!t) return { id: null, name: null, source: 'none' };
  if (CREATED_DIR_EXCLUDE.includes(t.toLowerCase())) return { id: null, name: t, source: 'excluded' };

  // Точное совпадение с названием справочника.
  const exactId = Object.keys(directions).find(k => directions[k] === t);
  if (exactId) return { id: exactId, name: t, source: 'created' };

  const aliasId = CREATED_DIR_ALIASES[t];
  if (aliasId) return { id: aliasId, name: directions[aliasId] || t, source: 'created' };

  return { id: null, name: t, source: 'unresolved' };
}
